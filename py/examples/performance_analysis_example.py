import numpy as np
import pandas as pd

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent))

from imp.backtesting import (
    PerformanceAnalyzer,
    RegimePerformanceAnalyzer,
    PerformanceConfig,
    PortfolioState,
    Order,
    TradeSignal,
    TradeAction,
    ProcessedSignal,
    SignalDirection,
)


def create_sample_data():
    """Create sample portfolio snapshots and orders for demonstration."""
    print("Creating sample data...")
    
    # Initialize portfolio
    initial_capital = 100000.0
    start_time = datetime(2024, 1, 1)
    portfolio = PortfolioState(initial_capital, start_time)
    
    # Simulate trading over 100 periods
    snapshots = []
    orders = []
    
    current_time = start_time
    current_price = 50000.0
    position = 0.0
    
    # Create regime data (3 regimes cycling)
    regime_states = []
    
    for i in range(100):
        current_time += timedelta(minutes=5)
        
        # Simulate price movement
        price_change = np.random.normal(0, 0.01)
        current_price *= (1 + price_change)
        
        # Determine regime (cycle through 3 regimes)
        regime_state = i % 3
        regime_states.append({'timestamp': current_time, 'regime_state': regime_state})
        
        # Generate trading signals based on regime
        if i % 10 == 0:  # Trade every 10 periods
            # Determine signal source based on regime
            if regime_state == 0:
                signal_source = 'ldc'
            elif regime_state == 1:
                signal_source = 'mr'
            else:
                signal_source = 'tsmom'
            
            # Create trade signal
            if position == 0:
                # Open position
                action = TradeAction.BUY
                side = 'buy'
                quantity = 1.0
            else:
                # Close position
                action = TradeAction.CLOSE_LONG
                side = 'sell'
                quantity = abs(position)
            
            # Create processed signal
            processed_signal = ProcessedSignal(
                timestamp=current_time,
                symbol='BTCUSDT',
                direction=SignalDirection.BUY if action == TradeAction.BUY else SignalDirection.SELL,
                strength=0.65,
                signal_source=signal_source,
                raw_signals={'ldc': 0.7, 'mr': 0.5, 'tsmom': 0.6, 'fusion': 0.65},
                regime_state=regime_state,
                regime_weights={'ldc': 0.4, 'mr': 0.3, 'tsmom': 0.3},
                metadata={}
            )
            
            # Create trade signal
            trade_signal = TradeSignal(
                trade_id=f"trade_{i}",
                timestamp=current_time,
                symbol='BTCUSDT',
                action=action,
                confidence=0.65,
                signal_source=signal_source,
                reasoning=f"Generated by {signal_source} in regime {regime_state}",
                processed_signal=processed_signal,
                metadata={}
            )
            
            # Create order
            order = Order(
                order_id=f"order_{i}",
                timestamp=current_time,
                symbol='BTCUSDT',
                side=side,
                quantity=quantity,
                price=current_price,
                order_type='market',
                trade_signal=trade_signal,
                position_size_method='percentage',
                risk_checks_passed={'all': True},
                metadata={
                    'signal_source': signal_source,
                    'regime_state': regime_state
                }
            )
            
            orders.append(order)
            
            # Update portfolio
            portfolio.update_from_order(order, current_price, commission=10.0, slippage=5.0)
            
            if side == 'buy':
                position = quantity
            else:
                position = 0.0
        
        # Update prices
        portfolio.update_prices({'BTCUSDT': current_price}, current_time)
        
        # Take snapshot
        snapshot = portfolio.take_snapshot(current_time)
        snapshots.append(snapshot)
    
    # Create regime DataFrame
    regime_df = pd.DataFrame(regime_states)
    
    print(f"Created {len(snapshots)} snapshots and {len(orders)} orders")
    print(f"Final portfolio value: ${portfolio.total_value:,.2f}")
    print(f"Total P&L: ${portfolio.total_pnl:,.2f} ({portfolio.return_pct:.2f}%)")
    
    return snapshots, orders, initial_capital, regime_df


