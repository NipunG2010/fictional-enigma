def demonstrate_benchmark_comparison():
    """Demonstrate benchmark comparison."""
    print("\n" + "="*80)
    print("BENCHMARK COMPARISON")
    print("="*80)
    
    # Create sample data
    snapshots, orders, initial_capital, regime_df = create_sample_data()
    
    # Create synthetic benchmark data (buy-and-hold)
    print("\nCreating benchmark data (buy-and-hold)...")
    benchmark_data = []
    start_price = 50000.0
    current_price = start_price
    
    for snapshot in snapshots:
        # Simulate benchmark price movement
        price_change = np.random.normal(0.0001, 0.008)  # Slightly positive drift
        current_price *= (1 + price_change)
        
        benchmark_data.append({
            'timestamp': snapshot.timestamp,
            'close': current_price
        })
    
    benchmark_df = pd.DataFrame(benchmark_data)
    
    # Initialize performance analyzer
    config = PerformanceConfig(
        benchmark_symbol='BTCUSDT',
        risk_free_rate=0.02
    )
    
    analyzer = PerformanceAnalyzer(config)
    
    # Compare to benchmark
    print("\nComparing to benchmark...")
    comparison = analyzer.compare_to_benchmark(
        snapshots, benchmark_df, initial_capital
    )
    
    # Display results
    print("\n--- Benchmark Comparison ---")
    print(f"Strategy Return: {comparison.strategy_return:.2%}")
    print(f"Benchmark Return: {comparison.benchmark_return:.2%}")
    print(f"Excess Return: {comparison.excess_return:.2%}")
    print(f"Alpha: {comparison.alpha:.4f}")
    print(f"Beta: {comparison.beta:.2f}")
    print(f"Information Ratio: {comparison.information_ratio:.2f}")
    print(f"Tracking Error: {comparison.tracking_error:.4f}")
    print(f"Correlation: {comparison.correlation:.2f}")


