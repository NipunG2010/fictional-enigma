def demonstrate_comprehensive_report():
    """Demonstrate comprehensive regime report generation."""
    print("\n" + "="*80)
    print("COMPREHENSIVE REGIME REPORT")
    print("="*80)
    
    # Create sample data
    snapshots, orders, initial_capital, regime_df = create_sample_data()
    
    # Initialize analyzers
    config = PerformanceConfig(
        risk_free_rate=0.02,
        regime_analysis=True,
        attribution_analysis=True
    )
    
    base_analyzer = PerformanceAnalyzer(config)
    regime_analyzer = RegimePerformanceAnalyzer(
        config,
        regime_names={0: "Bull", 1: "Bear", 2: "Sideways"}
    )
    
    # Calculate all metrics
    print("\nCalculating comprehensive metrics...")
    overall_metrics = base_analyzer.calculate_metrics(snapshots, orders, initial_capital)
    regime_metrics = regime_analyzer.analyze_by_regime(
        snapshots, orders, initial_capital, regime_df
    )
    signal_attributions = regime_analyzer.analyze_signal_attribution(
        orders, snapshots, initial_capital
    )
    
    # Generate report
    print("\nGenerating comprehensive report...")
    report = regime_analyzer.generate_regime_report(
        regime_metrics, signal_attributions, overall_metrics
    )
    
    # Display report summary
    print("\n--- Overall Performance ---")
    print(f"Total Return: {report['overall_performance']['total_return']:.2%}")
    print(f"Sharpe Ratio: {report['overall_performance']['sharpe_ratio']:.2f}")
    print(f"Max Drawdown: {report['overall_performance']['max_drawdown']:.2%}")
    
    print("\n--- Regime Analysis Summary ---")
    regime_summary = report['regime_analysis']['summary']
    print(f"Number of Regimes: {regime_summary['num_regimes']}")
    print(f"Best Regime: {regime_summary['best_regime']['name']} "
          f"({regime_summary['best_regime']['return']:.2%})")
    print(f"Worst Regime: {regime_summary['worst_regime']['name']} "
          f"({regime_summary['worst_regime']['return']:.2%})")
    
    print("\n--- Signal Attribution Summary ---")
    signal_summary = report['signal_attribution']['summary']
    print(f"Number of Signals: {signal_summary['num_signals']}")
    print(f"Best Signal: {signal_summary['best_signal']['source']} "
          f"(${signal_summary['best_signal']['pnl']:.2f})")
    print(f"Total Trades: {signal_summary['total_trades']}")
    print(f"Total P&L: ${signal_summary['total_pnl']:.2f}")


